import { fileURLToPath, pathToFileURL } from "node:url";
import {
  access,
  mkdir,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { getPublicImageConfig } from "../data/public-image-registry.js";
import { auditPublicImages, walkFiles } from "./public-image-audit.mjs";

export const ROLE_POLICIES = Object.freeze({
  "tool-cover": Object.freeze({ widths: [240, 320, 480, 640, 960, 1280, 1600], budget: 120 * 1024 }),
  "tutorial-cover": Object.freeze({ widths: [240, 320, 480, 640, 960, 1280], budget: 120 * 1024 }),
  portrait: Object.freeze({ widths: [96, 160, 240, 320, 480, 640], budget: 100 * 1024 }),
  "project-cover": Object.freeze({ widths: [320, 480, 640, 768, 960, 1280, 1600, 1920], budget: 180 * 1024 }),
  "interface-screenshot": Object.freeze({ widths: [320, 480, 640, 768, 960, 1280, 1600], budget: 180 * 1024 }),
  "gallery-evidence": Object.freeze({ widths: [320, 480, 640, 768, 960, 1280, 1600, 1920, 2560], budget: 260 * 1024 }),
  social: Object.freeze({ widths: [1200], budget: 300 * 1024 }),
  decorative: Object.freeze({ widths: [240, 320, 480, 640, 960, 1280], budget: 120 * 1024 }),
});
const RASTER_EXTENSION = /\.(?:avif|gif|jpe?g|png|webp)$/i;
const GENERATED_PREFIX = "/media/generated/responsive/";
const PIPELINE_PATH = fileURLToPath(import.meta.url);

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

function outputDirectory(rootDir, source) {
  const withoutExtension = source.replace(/^\//, "").replace(RASTER_EXTENSION, "");
  return path.join(rootDir, "public", "media", "generated", "responsive", withoutExtension);
}

function publicVariantPath(source, width, extension) {
  const withoutExtension = source.replace(/^\//, "").replace(RASTER_EXTENSION, "");
  return `${GENERATED_PREFIX}${withoutExtension}/${width}.${extension}`;
}

async function encodeToBudget(image, { format, width, budget, outputPath, write }) {
  const initialQuality = format === "avif" ? 55 : 78;
  const minimumQuality = format === "avif" ? 36 : 45;
  let quality = initialQuality;
  let buffer;
  do {
    const resized = image.clone().resize({ width, withoutEnlargement: true });
    buffer = format === "avif"
      ? await resized.avif({ quality, effort: 4 }).toBuffer()
      : await resized.webp({ quality, alphaQuality: quality, effort: 4 }).toBuffer();
    if (buffer.byteLength <= budget || quality === minimumQuality) break;
    quality = Math.max(minimumQuality, quality - 5);
  } while (quality >= minimumQuality);

  if (write) {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, buffer);
  }
  return { bytes: buffer.byteLength, quality };
}

function serializeManifest(assets) {
  const entries = Object.fromEntries(assets.map(asset => [asset.source, asset]));
  return `/* Generated by scripts/public-image-pipeline.mjs. Do not edit manually. */\n\n`
    + `export type PublicImageVariant = { src: string; width: number; bytes: number };\n`
    + `export type PublicImageAsset = { source: string; width: number; height: number; avif: PublicImageVariant[]; webp: PublicImageVariant[] };\n`
    + `export type PublicImageFamily = PublicImageAsset & { role: string; sizesPreset: string; mobile?: PublicImageAsset; wide?: PublicImageAsset };\n\n`
    + `export const publicImageManifest: Record<string, PublicImageFamily> = ${JSON.stringify(entries, null, 2)};\n`;
}

async function prepareAsset({ rootDir, source, policy, write, oversized }) {
  const sourcePath = path.join(rootDir, "public", source.replace(/^\//, ""));
  if (!(await exists(sourcePath))) return null;
  const image = sharp(sourcePath, { animated: false, failOn: "error" });
  const metadata = await image.metadata();
  const sourceStats = await stat(sourcePath);
  const pipelineStats = await stat(PIPELINE_PATH);
  if (!metadata.width || !metadata.height) return null;
  const widths = [...new Set([...policy.widths.filter((width) => width < metadata.width), metadata.width])]
    .sort((first, second) => first - second);
  const asset = { source, width: metadata.width, height: metadata.height, avif: [], webp: [] };
  const directory = outputDirectory(rootDir, source);

  for (const format of ["avif", "webp"]) {
    for (const width of widths) {
      const outputPath = path.join(directory, `${width}.${format}`);
      const outputStats = await exists(outputPath) ? await stat(outputPath) : null;
      const encoded = outputStats && outputStats.mtimeMs >= Math.max(sourceStats.mtimeMs, pipelineStats.mtimeMs)
        ? { bytes: outputStats.size, quality: null }
        : await encodeToBudget(image, { format, width, budget: policy.budget, outputPath, write });
      asset[format].push({ src: publicVariantPath(source, width, format), width, bytes: encoded.bytes });
      if (encoded.bytes > policy.budget) oversized.push({ source, format, width, bytes: encoded.bytes, budget: policy.budget });
    }
  }
  return asset;
}

export async function preparePublicImages({ rootDir = process.cwd(), write = false } = {}) {
  const audit = await auditPublicImages({ rootDir });
  const assets = [];
  const missing = [];
  const oversized = [];

  for (const item of audit.referenced) {
    const config = getPublicImageConfig(item.source);
    const policy = ROLE_POLICIES[config.role];
    const prepared = await prepareAsset({ rootDir, source: item.source, policy, write, oversized });
    if (!prepared) { missing.push(item.source); continue; }
    const family = { ...prepared, role: config.role, sizesPreset: config.sizesPreset };
    if (config.mobileSrc && await exists(path.join(rootDir, "public", config.mobileSrc.replace(/^\//, "")))) {
      family.mobile = await prepareAsset({ rootDir, source: config.mobileSrc, policy, write, oversized });
    }
    if (config.wideSrc && await exists(path.join(rootDir, "public", config.wideSrc.replace(/^\//, "")))) {
      family.wide = await prepareAsset({ rootDir, source: config.wideSrc, policy, write, oversized });
    }
    assets.push(family);
  }

  const unregistered = audit.referenced.filter((item) => !item.registered).map((item) => item.source);
  const directImgBypasses = audit.directImgUsages.filter((item) => item.file !== "components/PublicImage.tsx");
  const orphanCandidates = audit.unreferenced;

  if (write) {
    const manifestPath = path.join(rootDir, "data", "public-image-manifest.generated.ts");
    await mkdir(path.dirname(manifestPath), { recursive: true });
    await writeFile(manifestPath, serializeManifest(assets));
    await writeFile(path.join(rootDir, "data", "public-image-audit.generated.json"), `${JSON.stringify({
      generatedAt: new Date().toISOString(),
      roleCounts: audit.roleCounts,
      referenced: audit.referenced.length,
      unreferenced: audit.unreferenced,
      oversizedSources: audit.oversizedSources.map((item) => item.source),
      missing,
      oversized,
      unregistered,
      directImgBypasses
    }, null, 2)}\n`);
  }

  return { assets, missing, oversized, unregistered, directImgBypasses, orphanCandidates, allowlisted: [] };
}

async function runCli() {
  const write = process.argv.includes("--write");
  const check = process.argv.includes("--check");
  const report = await preparePublicImages({ write });
  const bytes = report.assets.reduce(
    (total, asset) => total + [...asset.avif, ...asset.webp].reduce((sum, variant) => sum + variant.bytes, 0),
    0
  );
  console.log(JSON.stringify({
    assets: report.assets.length,
    variantsBytes: bytes,
    missing: report.missing,
    oversized: report.oversized,
    unregistered: report.unregistered,
    directImgBypasses: report.directImgBypasses,
    orphanCandidates: report.orphanCandidates.length,
  }, null, 2));
  if ((check || write) && (report.missing.length || report.oversized.length || report.unregistered.length || report.directImgBypasses.length)) process.exitCode = 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await runCli();
}
