import { pathToFileURL } from "node:url";
import {
  access,
  mkdir,
  readFile,
  readdir,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

export const RESPONSIVE_WIDTHS = Object.freeze([320, 640, 960, 1280, 1600]);
export const BUDGETS = Object.freeze({
  portrait: 100 * 1024,
  cover: 180 * 1024,
  evidence: 300 * 1024,
});

const SOURCE_DIRECTORIES = Object.freeze(["app", "components", "content", "data", "lib"]);
const SOURCE_EXTENSIONS = new Set([".css", ".js", ".jsx", ".md", ".mdx", ".ts", ".tsx"]);
const RASTER_EXTENSION = /\.(?:avif|gif|jpe?g|png|webp)$/i;
const PUBLIC_RASTER_REFERENCE = /\/(?:blog|images|media)\/[A-Za-z0-9_@%+.,()\-/ ]+?\.(?:avif|gif|jpe?g|png|webp)/gi;
const GENERATED_PREFIX = "/media/generated/responsive/";

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function walkFiles(directory) {
  if (!(await exists(directory))) return [];
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walkFiles(entryPath));
    else if (entry.isFile()) files.push(entryPath);
  }
  return files;
}

function normalizePublicPath(value) {
  return value.replaceAll("\\", "/").replace(/\/+/g, "/");
}

async function discoverReferences(rootDir) {
  const references = new Set();
  for (const sourceDirectory of SOURCE_DIRECTORIES) {
    const files = await walkFiles(path.join(rootDir, sourceDirectory));
    for (const filePath of files) {
      if (!SOURCE_EXTENSIONS.has(path.extname(filePath).toLowerCase())) continue;
      if (filePath.endsWith("public-image-manifest.generated.ts")) continue;
      const source = await readFile(filePath, "utf8");
      for (const match of source.matchAll(PUBLIC_RASTER_REFERENCE)) {
        const precedingCharacter = source[(match.index ?? 0) - 1];
        if (precedingCharacter && /[A-Za-z0-9_.-]/.test(precedingCharacter)) continue;
        const publicPath = normalizePublicPath(match[0]);
        if (!publicPath.startsWith(GENERATED_PREFIX)) references.add(publicPath);
      }
    }
  }
  const explicitSourcesPath = path.join(rootDir, "data", "public-image-sources.json");
  if (await exists(explicitSourcesPath)) {
    const explicitSources = JSON.parse(await readFile(explicitSourcesPath, "utf8"));
    if (!Array.isArray(explicitSources) || explicitSources.some(source => typeof source !== "string" || !source.startsWith("/"))) {
      throw new Error("data/public-image-sources.json must be an array of root-relative public image paths");
    }
    explicitSources.forEach(source => references.add(normalizePublicPath(source)));
  }
  return [...references].sort();
}

function classifyImage(source) {
  const lower = source.toLowerCase();
  if (lower.includes("profile") || lower.includes("portrait")) return "portrait";
  if (lower.includes("cover") || lower.includes("/tools/") || lower.includes("/calculators/")) return "cover";
  return "evidence";
}

function outputDirectory(rootDir, source) {
  const withoutExtension = source.replace(/^\//, "").replace(RASTER_EXTENSION, "");
  return path.join(rootDir, "public", "media", "generated", "responsive", withoutExtension);
}

function publicVariantPath(source, width, extension) {
  const withoutExtension = source.replace(/^\//, "").replace(RASTER_EXTENSION, "");
  return `${GENERATED_PREFIX}${withoutExtension}/${width}.${extension}`;
}

async function encodeToBudget(image, { format, width, budget, outputPath, write }) {
  const initialQuality = format === "avif" ? 55 : 78;
  const minimumQuality = format === "avif" ? 40 : 60;
  let quality = initialQuality;
  let buffer;
  do {
    const resized = image.clone().resize({ width, withoutEnlargement: true });
    buffer = format === "avif"
      ? await resized.avif({ quality, effort: 4 }).toBuffer()
      : await resized.webp({ quality, effort: 4 }).toBuffer();
    if (buffer.byteLength <= budget || quality === minimumQuality) break;
    quality = Math.max(minimumQuality, quality - 5);
  } while (quality >= minimumQuality);

  if (write) {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, buffer);
  }
  return { bytes: buffer.byteLength, quality };
}

function serializeManifest(assets) {
  const entries = Object.fromEntries(assets.map(asset => [asset.source, asset]));
  return `/* Generated by scripts/public-image-pipeline.mjs. Do not edit manually. */\n\n`
    + `export type PublicImageVariant = { src: string; width: number; bytes: number };\n`
    + `export type PublicImageAsset = { source: string; width: number; height: number; avif: PublicImageVariant[]; webp: PublicImageVariant[] };\n\n`
    + `export const publicImageManifest: Record<string, PublicImageAsset> = ${JSON.stringify(entries, null, 2)};\n`;
}

export async function preparePublicImages({ rootDir = process.cwd(), write = false } = {}) {
  const references = await discoverReferences(rootDir);
  const assets = [];
  const missing = [];
  const oversized = [];

  for (const source of references) {
    const sourcePath = path.join(rootDir, "public", source.replace(/^\//, ""));
    if (!(await exists(sourcePath))) {
      missing.push(source);
      continue;
    }
    const image = sharp(sourcePath, { animated: false, failOn: "error" });
    const metadata = await image.metadata();
    const sourceStats = await stat(sourcePath);
    if (!metadata.width || !metadata.height) {
      missing.push(source);
      continue;
    }
    const widths = [...new Set([...RESPONSIVE_WIDTHS.filter(width => width < metadata.width), metadata.width])]
      .sort((first, second) => first - second);
    const budget = BUDGETS[classifyImage(source)];
    const asset = { source, width: metadata.width, height: metadata.height, avif: [], webp: [] };
    const directory = outputDirectory(rootDir, source);

    for (const format of ["avif", "webp"]) {
      for (const width of widths) {
        const outputPath = path.join(directory, `${width}.${format}`);
        const outputStats = await exists(outputPath) ? await stat(outputPath) : null;
        const encoded = outputStats && outputStats.mtimeMs >= sourceStats.mtimeMs
          ? { bytes: outputStats.size, quality: null }
          : await encodeToBudget(image, { format, width, budget, outputPath, write });
        const variant = { src: publicVariantPath(source, width, format), width, bytes: encoded.bytes };
        asset[format].push(variant);
        if (encoded.bytes > budget) oversized.push({ source, format, width, bytes: encoded.bytes, budget });
      }
    }
    assets.push(asset);
  }

  const publicRasterFiles = (await walkFiles(path.join(rootDir, "public")))
    .filter(filePath => RASTER_EXTENSION.test(filePath))
    .map(filePath => `/${path.relative(path.join(rootDir, "public"), filePath).replaceAll("\\", "/")}`)
    .filter(source => !source.startsWith(GENERATED_PREFIX));
  const referencedSet = new Set(references);
  const orphanCandidates = publicRasterFiles.filter(source => !referencedSet.has(source)).sort();

  if (write) {
    const manifestPath = path.join(rootDir, "data", "public-image-manifest.generated.ts");
    await mkdir(path.dirname(manifestPath), { recursive: true });
    await writeFile(manifestPath, serializeManifest(assets));
  }

  return { assets, missing, oversized, orphanCandidates, allowlisted: [] };
}

async function runCli() {
  const write = process.argv.includes("--write");
  const check = process.argv.includes("--check");
  const report = await preparePublicImages({ write });
  const bytes = report.assets.reduce(
    (total, asset) => total + [...asset.avif, ...asset.webp].reduce((sum, variant) => sum + variant.bytes, 0),
    0
  );
  console.log(JSON.stringify({
    assets: report.assets.length,
    variantsBytes: bytes,
    missing: report.missing,
    oversized: report.oversized,
    orphanCandidates: report.orphanCandidates.length,
  }, null, 2));
  if ((check || write) && (report.missing.length || report.oversized.length)) process.exitCode = 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await runCli();
}
